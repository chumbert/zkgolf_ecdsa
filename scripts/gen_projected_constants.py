#!/usr/bin/env python3
"""Generate literal constant tables for Solution/Projected/Constants.lean.

Computes:
- tableX tableY : Fin 128 → Fin 4 → Fp
  where tableX i d = ((4+d)·4^i•G).x
- shiftX shiftY : Fp
  where (shiftX, shiftY) = (4·(4^128−1)/3)•G

Uses the same computation as Baseline/Projected/Offset.lean:
  fixedTables[i][d] = affine(mulG((4+d)*4^i))
  fixedShift = affine(mulG(4*((4^128-1)/3)))

The Lean definitions use nested arrays with getD for Fin indexing.
"""

import sys

# P-256 parameters
p = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
n = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551

# Generator point G
G = (0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296,
     0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5)


def add(P, Q):
    """Affine point addition on P-256 curve."""
    if P is None:
        return Q
    if Q is None:
        return P
    x, y = P
    u, v = Q
    # Point at infinity check: x == u and y == -v mod p
    if x == u and (y + v) % p == 0:
        return None
    if P == Q:
        # Doubling: slope = (3*x^2 - 3) / (2*y)
        slope = ((3 * x * x - 3) * pow(2 * y, -1, p)) % p
    else:
        # Addition: slope = (v - y) / (u - x)
        slope = ((v - y) * pow(u - x, -1, p)) % p
    X = (slope * slope - x - u) % p
    return (X, (slope * (x - X) - y) % p)


def mul(k, P):
    """Scalar multiplication using double-and-add."""
    result = None
    while k:
        if k & 1:
            result = add(result, P)
        P = add(P, P)
        k >>= 1
    return result


def compute_fixed_tables():
    """Compute tableX and tableY as 2D arrays of natural numbers."""
    tables = []
    for i in range(128):
        row = []
        for d in range(4):
            # Compute ((4+d) * 4^i) mod n, then multiply by G
            scalar = (4 + d) * (4 ** i)
            # The code reduces mod n
            scalar_mod_n = scalar % n
            point = mul(scalar_mod_n, G)
            if point is None:
                raise ValueError(f"Point at infinity for i={i}, d={d}")
            row.append(point)
        tables.append(row)
    return tables


def compute_fixed_shift():
    """Compute shiftX and shiftY."""
    # Compute 4 * ((4^128 - 1) / 3) mod n
    # First compute 4^128
    pow_4_128 = pow(4, 128)
    # Then (4^128 - 1) / 3
    numerator = pow_4_128 - 1
    # Division by 3 mod n
    # We need the modular inverse of 3 mod n
    inv_3 = pow(3, -1, n)
    scalar = (4 * (numerator % n) * inv_3) % n
    point = mul(scalar, G)
    if point is None:
        raise ValueError("Point at infinity for shift")
    return point


def format_lean_nat_array_2d(arr):
    """Format a 2D Python list of natural numbers as a Lean nested array literal."""
    if not arr:
        return "#[]"
    
    inner_arrays = []
    for row in arr:
        inner = ", ".join(str(x) for x in row)
        inner_arrays.append("    #[" + inner + "]")
    
    return "#[\n" + ",\n".join(inner_arrays) + "\n  ]"


def generate_lean_file():
    """Generate the Constants.lean file."""
    tables = compute_fixed_tables()
    shift = compute_fixed_shift()
    
    # Extract X and Y coordinates
    tableX_values = []
    tableY_values = []
    for i in range(128):
        x_row = [tables[i][d][0] for d in range(4)]
        y_row = [tables[i][d][1] for d in range(4)]
        tableX_values.append(x_row)
        tableY_values.append(y_row)
    
    # Build the Lean code
    lines = []
    lines.append("/-")
    lines.append("Auto-generated by scripts/gen_projected_constants.py")
    lines.append("Do not edit manually.")
    lines.append("-/")
    lines.append("")
    lines.append("import Challenge.Specs.ECDSAP256")
    lines.append("")
    lines.append("namespace Solution.Projected")
    lines.append("")
    lines.append("abbrev Fp := Challenge.Specs.ECDSAP256.K")
    lines.append("")
    
    # Generate tableX and tableY as nested arrays
    tableX_str = format_lean_nat_array_2d(tableX_values)
    tableY_str = format_lean_nat_array_2d(tableY_values)
    
    # Store the arrays as private definitions
    lines.append("private def _tableX : Array (Array Fp) := " + tableX_str)
    lines.append("")
    lines.append("private def _tableY : Array (Array Fp) := " + tableY_str)
    lines.append("")
    
    # Define the public accessor functions
    lines.append("/-- X-coordinates: tableX i d = ((4+d)·4^i•G).x mod p -/")
    lines.append("def tableX : Fin 128 → Fin 4 → Fp := fun i d => (_tableX.getD i.val #[]).getD d.val 0")
    lines.append("")
    
    lines.append("/-- Y-coordinates: tableY i d = ((4+d)·4^i•G).y mod p -/")
    lines.append("def tableY : Fin 128 → Fin 4 → Fp := fun i d => (_tableY.getD i.val #[]).getD d.val 0")
    lines.append("")
    
    lines.append("/-- Shift point: S = (4·(4^128−1)/3)•G -/")
    lines.append("def shiftX : Fp := " + str(shift[0]))
    lines.append("def shiftY : Fp := " + str(shift[1]))
    lines.append("")
    lines.append("end Solution.Projected")
    lines.append("")
    
    return "\n".join(lines)


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Generate projected constants")
    parser.add_argument("--output", "-o", type=str, default=None,
                        help="Output file (default: Solution/Projected/Constants.lean)")
    parser.add_argument("--check", action="store_true",
                        help="Check against existing Baseline/Projected/Offset.lean")
    args = parser.parse_args()
    
    if args.check:
        # For checking, we need to compare with Offset.lean
        # But that's harder from Python, so we just print the values
        tables = compute_fixed_tables()
        shift = compute_fixed_shift()
        print(f"fixedShift: ({shift[0]}, {shift[1]})")
        print(f"fixedTables[0][0]: {tables[0][0]}")
        print(f"fixedTables[0][1]: {tables[0][1]}")
        print(f"fixedTables[0][2]: {tables[0][2]}")
        print(f"fixedTables[0][3]: {tables[0][3]}")
        print(f"fixedTables[1][0]: {tables[1][0]}")
    else:
        lean_code = generate_lean_file()
        
        output_path = args.output
        if output_path is None:
            output_path = "Solution/Projected/Constants.lean"
        
        with open(output_path, "w") as f:
            f.write(lean_code)
        
        print(f"Generated {output_path}")


if __name__ == "__main__":
    main()
