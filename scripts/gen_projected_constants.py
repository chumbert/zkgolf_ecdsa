#!/usr/bin/env python3
"""Emit Solution/Projected/Constants.lean with literal P-256 fixed-base tables.

Values are computed with the affine model from scripts/p256_reference.py and
must equal Baseline.Projected.Offset.fixedTables / fixedShift (checked
executably by `lake exe projected2 --constants-check`).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from p256_reference import p, n, G, mul


def fmt(v):
    return hex(v)


def main():
    tables = []  # tables[i][d] = (x, y) of (4+d)*4^i * G
    for i in range(128):
        row = []
        for d in range(4):
            row.append(mul((4 + d) * 4**i, G))
        tables.append(row)
    shift = mul(4 * ((4**128 - 1) // 3), G)

    xs = [[fmt(x) for (x, y) in row] for row in tables]
    ys = [[fmt(y) for (x, y) in row] for row in tables]

    def lean_list(nested):
        return "[" + ",".join("[" + ",".join(v) + "]" for v in nested) + "]"

    out = []
    out.append("import Solution.Projected.Types")
    out.append("import ECDSA.Ecdsa")
    out.append("")
    out.append("/-! Literal P-256 fixed-base constant tables, generated by")
    out.append("`scripts/gen_projected_constants.py`. Do not edit by hand. -/")
    out.append("namespace Solution.Projected")
    out.append("")
    out.append("open Challenge.Specs.ECDSAP256")
    out.append("")
    out.append("abbrev KP := ProjectivePoint Fp")
    out.append("")
    out.append("def affine (p : KP) : Fp × Fp := (p.X * p.Z⁻¹, p.Y * p.Z⁻¹)")
    out.append("def gPoint : KP := { X := gx, Y := gy, Z := 1 }")
    out.append("def mulG (k : Nat) : KP :=")
    out.append("  bsmul (padBits (natToBits (k % n)) 256) gPoint params")
    out.append("")
    out.append("def tableXList : List (List Fp) := " + lean_list(xs))
    out.append("def tableYList : List (List Fp) := " + lean_list(ys))
    out.append("")
    out.append("def tableX (i : Fin 128) (d : Fin 4) : Fp := (tableXList.getD i.val []).getD d.val 0")
    out.append("def tableY (i : Fin 128) (d : Fin 4) : Fp := (tableYList.getD i.val []).getD d.val 0")
    out.append("")
    out.append("def shiftX : Fp := " + fmt(shift[0]))
    out.append("def shiftY : Fp := " + fmt(shift[1]))
    out.append("")
    out.append("/-- The fixed-base tables as literal pairs, in the shape the circuit consumes. -/")
    out.append("def fixedTables : Array (Array (Fp × Fp)) :=")
    out.append("  (List.finRange 128).toArray.map fun i =>")
    out.append("    (List.finRange 4).toArray.map fun d => (tableX i d, tableY i d)")
    out.append("")
    out.append("def fixedShift : Fp × Fp := (shiftX, shiftY)")
    out.append("")
    out.append("end Solution.Projected")
    out.append("")

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "..", "Solution", "Projected", "Constants.lean")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
